"""Recover a pre-admitted synthetic owner request and one real context correction across Tasks and Conversation.

No generative model is launched. The initial completed attempt is explicitly
synthetic; actual HTTP replay, Stop and correction identity are independently checked.
"""

import argparse
from contextlib import closing
import hashlib
import json
import os
from pathlib import Path
import socket
import sqlite3
import subprocess
import sys

from host_smoke import start, stop
from task_creation_page import observe as original_observe, seed as original_seed

ROOT = Path(__file__).resolve().parents[2]


def seed(host):
    """Pre-admit the exact synthetic owner request and close never-launched logical peers before serving."""
    from backend.db.connection import connect
    from backend.runtime.contracts import RunSpec
    from backend.runtime.peer_registry import AttemptPeers
    from backend.runtime.sqlite_runs import SQLiteRunStore
    from backend.runtime.views import OwnerRuntimeView
    from backend.runtime.workspaces import WorkspaceRegistry

    ids = original_seed(host)
    source = host/'sources'/'observations'
    source.mkdir()
    (source/'observations.py').write_text('"""Synthetic observation data; no code is executed by this evaluation."""\nobservations = [{"id": 7, "measurement": 12}]\n')
    with closing(connect(host/'source.db')) as db, db:
        db.execute("INSERT INTO repositories(id,project_id,name,local_path) VALUES(11,101,'observaciones',?)",(str(source),))
    runs = SQLiteRunStore(host/'source.db')
    runs.context_snapshot(101,ids['output'])
    version = runs.context_snapshot(101,ids['input'])['context_version']
    body = {'operation_key':'synthetic-original-instruction','task_id':ids['input'],'context_version':version,'thread_id':'synthetic-original-thread','message':'Describe los campos de una observación y cómo se relacionan con las columnas del CSV. Primero muestra una entrada y la salida esperada; distingue el ejemplo de lo comprobado.','repository_id':11}
    run = runs.admit(RunSpec(101,ids['input'],'researcher',version,body['operation_key'],body['message'],'codex'),binding=WorkspaceRegistry(host/'source.db',host/'sources').bind(101,11),conversation_thread=body['thread_id'])
    lease,peers = AttemptPeers.claim(runs,101,run.run_id,'synthetic-never-launched-owner')
    try:
        for peer in peers.ids.values():
            peers.registry.close(peer)
        runs.finish(lease,native_status='completed',summary='Synthetic fixture only: this proposal was not generated by a model.')
    except BaseException:
        for peer in peers.ids.values():
            peers.registry.close(peer)
        runs.cancel(101,run.run_id)
        runs.retire_inference(lease,outcome='cancelled')
        raise
    message = OwnerRuntimeView(host/'source.db').instruction_message(101,run.run_id)
    assert message['thread_id']==body['thread_id'] and message['message']==body['message']
    ids.update(run=run.run_id,packet={'schema':1,'kind':'instruction','projectId':101,'taskId':ids['input'],'body':body})
    return ids


def observe(host):
    """Observe original metadata, source bytes and exact context/correction receipts without trusting UI success labels."""
    result = original_observe(host)
    with closing(sqlite3.connect(host/'source.db')) as db:
        db.row_factory = sqlite3.Row
        result['contexts'] = [dict(row) for row in db.execute('SELECT task_id,version FROM task_contexts ORDER BY task_id')]
        result['corrections'] = [dict(row) for row in db.execute('SELECT project_id,task_id,version,statement,source_kind,source_reference FROM runtime_context_revisions ORDER BY project_id,task_id,version')]
        result['controls'] = [dict(row) for row in db.execute('SELECT project_id,task_id,operation_key,result_json FROM runtime_commands ORDER BY project_id,task_id,operation_key')]
    result['source_sha256'] = hashlib.sha256((host/'sources/observations/observations.py').read_bytes()).hexdigest()
    return result


def verify_postconditions(ids,before,after,evidence):
    """Check original captured domain observations without repeating owner decisions or inferring absent contexts as version zero."""
    expected_runs = json.loads(json.dumps(before['runs']))
    expected_runs[0]['status'] = 'cancelled'
    assert after['runs']==expected_runs
    assert all(after[key]==before[key] for key in ('groups','milestones','tasks','task_records','dependencies','owner_commands','peers','dispatches','native_starts','integrity','foreign_keys','source_sha256'))
    versions={item['task_id']:item['version'] for item in before['contexts']}
    for task in (ids['input'],ids['output']):
        versions[task]=versions.get(task,1)+1
    expected_contexts=[{'task_id':task,'version':version} for task,version in sorted(versions.items())]
    assert after['contexts']==expected_contexts
    assert len(after['corrections'])==len(before['corrections'])+2
    dependents=[item for item in after['corrections'] if item['task_id']==ids['output']]
    assert len(dependents)==1 and dependents[0]['version']==2 and dependents[0]['source_kind']=='tool_evidence'
    correction = evidence['corrections'][0]['body']
    row = next(row for row in after['corrections'] if row['source_reference']=='owner-correction:'+correction['operation_key'])
    assert row['version']==correction['expected_version']+1 and row['statement']==correction['statement'] and row['source_kind']==correction['source_kind']
    controls = [row for row in after['controls'] if row['operation_key']==correction['operation_key']]
    assert len(controls)==1 and json.loads(controls[0]['result_json'])=={'version':row['version']}
    return row


def main():
    """Own the installed host/browser and prove replay/Stop/correction cannot create another run or context revision."""
    import backend
    from backend.runtime.host_installation import initialize_host

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--assets',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--node',type=Path,required=True)
    args = parser.parse_args()
    if not Path(backend.__file__).resolve().is_relative_to(Path(sys.prefix).resolve()):
        raise RuntimeError('Use the separately installed product Python')
    output = args.output.resolve()
    output.mkdir(mode=0o700)
    assets = json.loads(args.assets.read_text())
    token = output / 'synthetic-account.json'
    with token.open('x') as stream:
        os.chmod(token,0o600)
        json.dump({'auth_mode':'chatgpt','tokens':{'access_token':'synthetic.header.signature','account_id':'synthetic-task-requests'}},stream)
    assets.update(token_file=str(token),static_dir=str(ROOT/'frontend/dist'))
    assets.pop('storage',None)
    host = output/'host'
    initialize_host(host,witness_dir=output/'witness',assets=assets)
    fixture = output/'fixture.json'
    ids = seed(host)
    fixture.write_text(json.dumps(ids,indent=2)+'\n')
    before = observe(host)
    assert len(before['runs'])==1 and before['runs'][0]['status']=='needs_review' and before['dispatches']==before['native_starts']==0
    assert all(peer['state']=='closed' for peer in before['peers'])
    result = {'status':'running','model_turns':0,'synthetic_project_data':True,'before':before,'backend':str(Path(backend.__file__).resolve()),'web_index_sha256':hashlib.sha256((ROOT/'frontend/dist/index.html').read_bytes()).hexdigest()}
    with socket.socket() as binding:
        binding.bind(('127.0.0.1',0))
        port = binding.getsockname()[1]
    process = log = None
    try:
        process,log = start(host,output,port,1)
        keys = list((host/'auth').glob('owner-*.key'))
        if len(keys)!=1:
            raise RuntimeError('Expected one private synthetic owner key')
        env = {**os.environ,'RESEARCHER_E2E_ORIGIN':f'http://127.0.0.1:{port}','RESEARCHER_E2E_OWNER_FILE':str(keys[0]),'RESEARCHER_E2E_OUTPUT':str(output/'browser'),'RESEARCHER_E2E_FIXTURE':str(fixture)}
        with (output/'browser.log').open('x') as browser_log:
            browser = subprocess.run([str(args.node.resolve(strict=True)),'tests/task-requests.e2e.mjs'],cwd=ROOT/'frontend',env=env,stdout=browser_log,stderr=subprocess.STDOUT,check=False,timeout=180)
        result['browser_exit'] = browser.returncode
        assert browser.returncode == 0, 'Inspect original browser log'
        evidence = json.loads((output/'browser/evidence.json').read_text())
        after = observe(host)
        row=verify_postconditions(ids,before,after,evidence)
        result.update(status='passed',original_run_id=ids['run'],final_context_version=row['version'])
    except BaseException as error:
        result.update(status='failed',error_type=type(error).__name__)
        raise
    finally:
        if process is not None:
            result['service_exit'] = stop(process,log)
        result['after'] = observe(host)
        (output/'result.json').write_text(json.dumps(result,indent=2)+'\n')
        print(json.dumps({'status':result['status'],'receipt':str(output/'result.json')}),flush=True)


if __name__=='__main__':
    main()
